import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
await fs.mkdir('test-results',{recursive:true});
const browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
const page=await browser.newPage();page.setDefaultTimeout(60000);const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto(process.env.TEST_URL??'http://localhost:5173/');
await page.getByRole('button',{name:'Texto a señas',exact:true}).click();
await page.getByLabel(/tu frase/i).fill('¡Hola, Perú! Niño jj 👍');
assert.equal(await page.locator('.sequence-sign').count(),22);
assert.equal(await page.locator('.sequence-sign img[alt="Seña de Ñ"]').count(),1);
await page.getByRole('button',{name:'Paso 4: L',exact:true}).click();
await page.getByAltText('Seña de la letra L',{exact:true}).waitFor();
await page.getByRole('button',{name:'Volver al inicio',exact:true}).click();
await page.getByRole('button',{name:'Reproducir',exact:true}).click();
await page.waitForTimeout(1700);assert.equal(await page.locator('.sequence-active strong').innerText(),'H');
await page.getByRole('button',{name:'Pausar',exact:true}).click();
await page.waitForTimeout(1700);assert.equal(await page.locator('.sequence-active strong').innerText(),'H');
assert.equal(await page.locator('video').count(),0);
await page.screenshot({path:'test-results/text-signs-desktop.png',fullPage:true});
await page.setViewportSize({width:360,height:800});
await page.getByLabel(/tu frase/i).fill('J Ñ Z');
await page.getByText('J requiere movimiento.',{exact:false}).waitFor();
assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
await page.screenshot({path:'test-results/text-signs-mobile.png',fullPage:true});
await page.getByRole('button',{name:'Alfabeto',exact:true}).click();assert.equal(await page.locator('.letter-card').count(),27);
await page.getByRole('button',{name:'Traductor',exact:true}).click();await page.getByRole('button',{name:'Activar cámara',exact:true}).waitFor();
await page.getByRole('button',{name:'Texto a señas',exact:true}).click();
await page.getByLabel(/tu frase/i).fill('');assert.equal(await page.locator('.sequence-sign').count(),0);
assert.equal(await page.getByRole('button',{name:'Reproducir',exact:true}).isDisabled(),true);
assert.deepEqual(errors,[]);console.log('UI texto/señas: secuencia, Ñ, reproducción/pausa, movimiento, móvil y tres pestañas OK');await browser.close();
